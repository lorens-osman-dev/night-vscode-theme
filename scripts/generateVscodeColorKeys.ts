/**
 * Generates src/types/vscodeColorKeys.d.ts — the union of every theme color key
 * VS Code registers in its runtime color registry (the same registry that powers
 * the autocomplete you get for `workbench.colorCustomization` in settings.json).
 *
 * Sources:
 * - Official reference page, which is generated from the runtime registry:
 *   https://code.visualstudio.com/api/references/theme-color
 *   (needed because many colors are registered in component files outside
 *   src/vs/platform/theme/common/colors/, e.g. titleBar.*, statusBar.*, tab.*)
 * - Fallback: for each source file of the registry, the first argument of
 *   registerColor("...") from microsoft/vscode main.
 *
 * Run with: bun run update-color-keys
 * Re-run whenever you bump the `engines.vscode` version in package.json.
 */

import { writeFileSync } from "node:fs";

/** Keys that appear in the reference page's prose but are settings, not colors. */
const NOT_COLOR_KEYS = new Set([
	"workbench.colorCustomizations",
	"editor.tokenColorCustomizations",
]);

const RAW_BASE =
	"https://raw.githubusercontent.com/microsoft/vscode/main/src/vs/platform/theme/common/colors";

const INDEX_URL =
	"https://api.github.com/repos/microsoft/vscode/contents/src/vs/platform/theme/common/colors";

const keySet = new Set<string>();

try {
	const html = await (await fetch("https://code.visualstudio.com/api/references/theme-color")).text();
	for (const match of html.matchAll(/<code>\s*([a-zA-Z][a-zA-Z0-9]*(?:\.[a-zA-Z0-9]+)+)\s*<\/code>/g)) {
		if (!NOT_COLOR_KEYS.has(match[1])) {
			keySet.add(match[1]);
		}
	}
} catch (error) {
	console.warn("Could not fetch the theme-color reference page, falling back to source files only.", error);
}

try {
	const files: { name: string; type: string }[] = await (await fetch(INDEX_URL)).json();
	for (const file of files) {
		if (file.type !== "file" || !file.name.endsWith(".ts") || file.name === "utils.ts") continue;
		const source = await (await fetch(`${RAW_BASE}/${file.name}`)).text();
		for (const match of source.matchAll(/registerColor\(['"`]([^'"`]+)['"`]/g)) {
			keySet.add(match[1]);
		}
	}
} catch (error) {
	console.warn("Could not fetch microsoft/vscode source files.", error);
}

const sortedKeys = [...keySet].sort();

if (sortedKeys.length === 0) {
	throw new Error("No color keys extracted — check network access and the page/source layout.");
}

const output = `// This file is generated by scripts/generateVscodeColorKeys.ts. Do not edit by hand.
// Source: VS Code theme color registry (${sortedKeys.length} color ids).
// Keys are sorted alphabetically so diffs stay readable.

export type TVsCodeColorKey =
${sortedKeys.map((key) => `\t| "${key}"`).join("\n")};
`;

writeFileSync(new URL("../src/types/vscodeColorKeys.d.ts", import.meta.url), output);

console.log(`Wrote src/types/vscodeColorKeys.d.ts with ${sortedKeys.length} color keys.`);
